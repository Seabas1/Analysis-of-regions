def box(slide, text, left, top, width, height, size=14, bold=False, color=GRAPHITE,
        align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, line_spacing=1.0):
    tb = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    for i, chunk in enumerate(text.split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = line_spacing
        r = p.add_run()
        r.text = chunk
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.color.rgb = color
        r.font.name = FONT
    return tb


def content(title, subtitle=None):
    s = prs.slides.add_slide(prs.slide_layouts[LAYOUT_TEXT])
    s.shapes.title.text = title
    for ph in list(s.placeholders):
        if ph != s.shapes.title:
            ph._element.getparent().remove(ph._element)
    if subtitle:
        box(s, subtitle, 0.62, 1.16, 11.6, 0.35, size=11.5, color=GRAPHITE)
    box(s, str(len(prs.slides)), 12.35, 6.98, 0.6, 0.35, size=10, color=RED_DARK,
        align=PP_ALIGN.RIGHT, bold=True)
    return s


def card(slide, left, top, width, height, fill=LIGHT):
    sh = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(left), Inches(top),
                                Inches(width), Inches(height))
    sh.adjustments[0] = 0.08
    sh.fill.solid()
    sh.fill.fore_color.rgb = fill
    sh.line.fill.background()
    sh.shadow.inherit = False
    return sh


def kpi_row(slide, items, top, height=1.25, size_val=22, size_lab=10.5, left=0.62, right=12.67):
    n = len(items)
    gap = 0.2
    width = (right - left - gap * (n - 1)) / n
    for i, (value, label) in enumerate(items):
        x = left + i * (width + gap)
        card(slide, x, top, width, height)
        box(slide, value, x + 0.08, top + 0.13, width - 0.16, 0.5, size=size_val, bold=True,
            color=RED_DARK, align=PP_ALIGN.CENTER)
        box(slide, label, x + 0.08, top + 0.68, width - 0.16, 0.5, size=size_lab,
            color=GRAPHITE, align=PP_ALIGN.CENTER, line_spacing=0.95)


def bullets(slide, items, left=0.62, top=1.5, width=12.05, height=5.2, size=13.5, gap=9,
            color=DARK):
    tb = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = tb.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap)
        r = p.add_run()
        r.text = "•  " + item
        r.font.size = Pt(size)
        r.font.color.rgb = color
        r.font.name = FONT
    return tb


def table(slide, rows, left, top, width, ratios, row_h=0.4, size=10.5):
    n_rows, n_cols = len(rows), len(rows[0])
    tbl = slide.shapes.add_table(n_rows, n_cols, Inches(left), Inches(top), Inches(width),
                                 Inches(row_h * n_rows)).table
    for i, r in enumerate(ratios):
        tbl.columns[i].width = Inches(width * r)
    for r, row in enumerate(rows):
        for c, text in enumerate(row):
            cell = tbl.cell(r, c)
            cell.text = text
            run = cell.text_frame.paragraphs[0].runs[0]
            run.font.size = Pt(size)
            run.font.bold = (r == 0)
            run.font.color.rgb = WHITE if r == 0 else DARK
            run.font.name = FONT
            cell.fill.solid()
            cell.fill.fore_color.rgb = RED_DARK if r == 0 else (LIGHT if r % 2 else WHITE)
            cell.margin_left = cell.margin_right = Inches(0.07)
            cell.margin_top = cell.margin_bottom = Inches(0.02)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
    return tbl


def chart(slide, kind, cats, series, left, top, width, height, number_format="0.0",
          legend=False, labels=True, colors=None, label_size=10):
    data = CategoryChartData()
    data.categories = cats
    for name, values in series:
        data.add_series(name, values)
    gf = slide.shapes.add_chart(kind, Inches(left), Inches(top), Inches(width), Inches(height), data)
    ch = gf.chart
    ch.font.size = Pt(10.5)
    ch.font.name = FONT
    ch.has_title = False
    ch.has_legend = legend
    if legend:
        ch.legend.position = XL_LEGEND_POSITION.BOTTOM
        ch.legend.include_in_layout = False
        ch.legend.font.size = Pt(9.5)
    plot = ch.plots[0]
    plot.has_data_labels = labels
    if kind in (XL_CHART_TYPE.PIE, XL_CHART_TYPE.DOUGHNUT):
        dl = plot.data_labels
        dl.show_value = True
        dl.show_percentage = False
        dl.number_format = '0.0"%"'
        dl.number_format_is_linked = False
        dl.font.size = Pt(label_size)
        dl.font.bold = True
        dl.font.color.rgb = WHITE
        if colors:
            for i, point in enumerate(plot.series[0].points):
                point.format.fill.solid()
                point.format.fill.fore_color.rgb = colors[i % len(colors)]
    else:
        plot.gap_width = 60
        dl = plot.data_labels
        dl.number_format = number_format
        dl.number_format_is_linked = False
        dl.font.size = Pt(label_size)
        dl.font.bold = True
        dl.font.color.rgb = RED_DARK
        if colors:
            for i, sr in enumerate(ch.series):
                sr.format.fill.solid()
                sr.format.fill.fore_color.rgb = colors[i % len(colors)]
        ch.value_axis.has_major_gridlines = True
        ch.value_axis.major_gridlines.format.line.color.rgb = RULE
        ch.value_axis.tick_labels.font.size = Pt(9.5)
        ch.category_axis.tick_labels.font.size = Pt(9.5)
    return ch


